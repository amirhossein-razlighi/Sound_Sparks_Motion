#!/usr/bin/env python3
"""Aggregate everything that exists into results_root/summary.md (+ rsync_list.txt). Safe to rerun anytime."""
from __future__ import annotations

import csv
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

from common import FIVE, OUT_ROOT, TWELVE, paper_run_dir

R = OUT_ROOT
REPO = Path(__file__).resolve().parents[2]
MODELS = [("loop_qwen25", "loop_yes_prob", "Qwen2.5 (in-loop critic, per-scenario settings)"),
          ("qwen25", "yes_prob", "Qwen2.5-VL-7B (16f protocol)"),
          ("qwen3vl", "yes_prob", "Qwen3-VL-8B (held-out)"),
          ("internvl3", "yes_prob", "InternVL3-8B (held-out)")]
CMP_ORDER = ["ours", "ltx2_retake", "lora_edit", "runway_aleph", "kiwi_edit", "uniedit", "vace_wan", "vace_ltx", "input"]
CTRL_ORDER = ["paper_ours", "zero", "random_s42", "random_s1", "lora_audio_r64", "lora_all_r64", "zvid", "ctrl_baseline", "paper_baseline"]


def load_scores(d: Path):
    out = {}
    for f, col, _ in MODELS:
        p = d / f"{f}.csv"
        if p.exists():
            for r in csv.DictReader(open(p)):
                if r.get(col) not in ("", None) and not r.get("error"):
                    out[(f, r["id"])] = float(r[col])
    mac = REPO / "results_mac" / "gemma3_12b_4bit.csv"
    return out, mac


def fmt(v, n=3):
    return "-" if v is None else f"{v:.{n}f}"


def method_table(scores, rows, order, title, extra_models=()):
    by = defaultdict(list)
    for r in rows:
        by[r["method"]].append(r["id"])
    models = [m for m in MODELS if any((m[0], i) in scores for i in (x["id"] for x in rows))] + list(extra_models)
    if not models:
        return [f"### {title}", "(no scores yet)", ""]
    head = "| method | n | " + " | ".join(f"{m[2]} mean / TS@0.5" for m in models) + " |"
    lines = [f"### {title}", "", head, "|" + "---|" * (len(models) + 2)]
    for meth in order:
        ids = by.get(meth, [])
        if not ids:
            continue
        cells = []
        for m in models:
            v = [scores[(m[0], i)] for i in ids if (m[0], i) in scores]
            cells.append(f"{st.mean(v):.3f} / {sum(x >= 0.5 for x in v)}/{len(v)}" if v else "-")
        lines.append(f"| {meth} | {len(ids)} | " + " | ".join(cells) + " |")
    return lines + [""]


def manifest(name):
    p = R / "manifests" / f"{name}.csv"
    return list(csv.DictReader(open(p))) if p.exists() else []


def main():
    L = ["# Rebuttal experiments - summary (auto-generated by editing/iclr_rebuttal/make_summary.py)", "",
         "All numbers are from the CURRENT code (seed-42 render differs from the April paper render by MAD 0.117 on [0,1];",
         "see README). Critic yes-probs are bf16-quantised. TS@0.5 = #videos with yes_prob >= 0.5.", ""]
    rsync = []
    scores, mac = load_scores(R / "heldout")
    bscores, _ = load_scores(R / "heldout_bon")
    scores.update(bscores)
    macs = {}
    if mac.exists():
        for r in csv.DictReader(open(mac)):
            if r.get("yes_prob") not in ("", None) and not r.get("error"):
                macs[("gemma3", r["id"])] = float(r["yes_prob"])
    scores.update(macs)
    gem = [("gemma3", "yes_prob", "Gemma-3-12B 4-bit (MAC, held-out)")] if macs else []

    # ---------------- P1
    L += ["## P1 - best-of-N prompt-only Retake vs ours (N = 3: seeds 42, 0, 1)", ""]
    sp = R / "best_of_n" / "summary.md"
    if sp.exists():
        L += sp.read_text().splitlines()[2:] + [""]
        bon = manifest("best_of_n")
        cmp_rows = [r for r in manifest("comparisons") if r["method"] in ("ours", "ltx2_retake")]
        pr = [dict(r, method="BoN-3 pick") for r in bon if r["method"] == "bon3"] + cmp_rows
        sc2 = dict(scores)
        for r in bon:
            if r["method"] == "bon3":
                for m in MODELS:
                    if (m[0], r["id"]) in scores:
                        sc2[(m[0], r["id"])] = scores[(m[0], r["id"])]
        L += method_table(sc2, pr, ["ours", "BoN-3 pick", "ltx2_retake"], "P1 picks scored by every critic", gem)
        for s in TWELVE:
            for f in ("bon3.mp4", "ours.mp4", "retake_seed42.mp4", "paper_retake_baseline.mp4"):
                rsync.append(str(R / "best_of_n" / "selected" / s / f))
    else:
        L += ["(not run yet)", ""]

    # ---------------- P2
    L += ["## P2 - held-out verifiers", ""]
    L += method_table(scores, manifest("comparisons"), CMP_ORDER, "12-scenario comparison videos (paper)", gem)
    L += method_table(scores, manifest("controls"), CTRL_ORDER,
                      "Rebuttal controls, 8 scenarios (ctrl_baseline = the controls' own prompt-only render)", gem)

    # ---------------- P3 / P4
    def run_row(d: Path):
        t = json.loads((d / "timing.json").read_text()) if (d / "timing.json").exists() else {}
        mode = next((p.name[5:] for p in d.glob("mode_*")), "both")
        bp = d / f"mode_{mode}" / f"best_params_{mode}.pt"
        log = d / f"mode_{mode}" / f"optimization_log_qwen_{mode}.csv"
        r = {"status": "OOM" if (d / "OOM.json").exists() else ("done" if (d / f"mode_{mode}" / f"best_optimized_video_{mode}.mp4").exists() else "running/failed")}
        if log.exists():
            rows = list(csv.DictReader(open(log)))
            if rows:
                b = min(rows, key=lambda x: float(x["total_loss"]))
                r.update(best_iter=int(b["iter"]), best_yes=float(b["qwen_yes_prob"]), best_total=float(b["total_loss"]), n_iter=len(rows))
        r.update(s_iter=t.get("mean_iter_s_post_warmup"), peak=t.get("peak_mem_gb_loop"))
        m = d / "metrics.json"
        if m.exists():
            mm = json.loads(m.read_text())["metrics"]
            r.update(motion_ratio=mm.get("motion_strength_ratio"), lpips=mm.get("source_preservation_lpips"))
        return r

    L += ["## P3 - back-propagation window K (audio_opt_last_steps)", "",
          "| scenario | K | status | best iter / n | loop-critic best yes (training render) | best total loss | s/iter | peak GB | RAFT motion ratio vs own baseline | LPIPS vs own baseline |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for s in FIVE:
        pr = paper_run_dir(s) / "mode_both" / "optimization_log_qwen_both.csv"
        if pr.exists():
            rows = list(csv.DictReader(open(pr)))
            b = min(rows, key=lambda x: float(x["total_loss"]))
            L.append(f"| {s} | 8 (paper run, April code) | done | {b['iter']} / {len(rows)} | {float(b['qwen_yes_prob']):.3f} | {float(b['total_loss']):.3f} | - | - | - | - |")
        for tag in ("K2", "K4", "K8_rerun", "K12"):
            d = R / "bp_window" / s / tag
            trl = REPO / "results_trillium" / "bp_window" / s / tag
            if not d.exists() and not trl.exists():
                continue
            r = run_row(d) if d.exists() else {"status": "on TRILLIUM"}
            L.append(f"| {s} | {tag[1:]} | {r['status']} | {r.get('best_iter','-')} / {r.get('n_iter','-')} | {fmt(r.get('best_yes'))} | "
                     f"{fmt(r.get('best_total'))} | {fmt(r.get('s_iter'),1)} | {fmt(r.get('peak'),1)} | {fmt(r.get('motion_ratio'),2)} | {fmt(r.get('lpips'))} |")
            if d.exists():
                rsync += [str(d / "baseline_video.mp4"), str(d / "mode_both" / "best_optimized_video_both.mp4")]
    L += ["", "## P4 - seeds (TRILLIUM; see results_trillium/opt_runs.csv)", ""]
    oc = REPO / "results_trillium" / "opt_runs.csv"
    if oc.exists():
        rows = list(csv.DictReader(open(oc)))
        L += ["| exp | scenario | tag | status | best_iter | best_qwen_yes | s/iter | peak GB | gpu |", "|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            L.append(f"| {r.get('exp')} | {r.get('scenario')} | {r.get('tag')} | {r.get('status')} | {r.get('best_iter')} | {r.get('best_qwen_yes')} | "
                     f"{r.get('mean_iter_s_post_warmup')} | {r.get('peak_mem_gb_loop')} | {r.get('gpu','')} |")
    else:
        L += ["(no TRILLIUM rows yet)"]
    L += [""]

    # ---------------- P5
    L += ["## P5 - transfer", ""]
    t5 = R / "transfer" / "summary.md"
    L += (t5.read_text().splitlines()[1:] if t5.exists() else ["(not analysed yet)"]) + [""]
    tg = R / "transfer" / "targets.csv"
    if tg.exists():
        for r in csv.DictReader(open(tg)):
            o = Path(r["out_dir"])
            rsync += [str(o / "transfer_both.mp4"), str(o / "baseline_video.mp4")]

    # ---------------- P7
    L += ["## P7 - temporal metrics", ""]
    fw = R / "p7" / "flow_warp.csv"
    if fw.exists():
        by = defaultdict(list)
        for r in csv.DictReader(open(fw)):
            if not r["error"]:
                by[(r["group"], r["method"])].append((float(r["flow_mag"]), float(r["warp_err"])))
        L += ["| group | method | n | RAFT flow magnitude (px, 512-wide) | warp error (L1, non-occluded) |", "|---|---|---|---|---|"]
        for (g, m), v in sorted(by.items()):
            L.append(f"| {g} | {m} | {len(v)} | {st.mean(a for a, _ in v):.2f} | {st.mean(b for _, b in v):.4f} |")
    vb = R / "p7" / "vbench_per_video.csv"
    if vb.exists():
        by = defaultdict(list)
        for r in csv.DictReader(open(vb)):
            by[(r["method"], r["dim"])].append(float(r["score"]))
        dims = sorted({d for _, d in by})
        meths = sorted({m for m, _ in by})
        L += ["", "| method | " + " | ".join(dims) + " |", "|---|" + "---|" * len(dims)]
        for m in meths:
            L.append(f"| {m} | " + " | ".join(fmt(st.mean(by[(m, d)]) if by.get((m, d)) else None, 4) for d in dims) + " |")
    L += [""]
    (R / "summary.md").write_text("\n".join(L) + "\n")
    (R / "rsync_list.txt").write_text("\n".join(p for p in rsync if Path(p).exists()) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
